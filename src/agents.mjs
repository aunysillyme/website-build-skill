import fs from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CORE, owned } from './bundle.mjs';

const packageRoot = fileURLToPath(new URL('../', import.meta.url));

export const ROLES = Object.freeze([
  { id: 'researcher', description: 'Research current web standards, stacks, and references before design or code.' },
  { id: 'coordinator', description: 'Confirm scope, track gates, and coordinate handoffs across stages.' },
  { id: 'designer', description: 'Extract brand tokens and produce three visual directions before site code.' },
  { id: 'graphics', description: 'Prepare visual assets, crop inspections, and responsive image deliverables.' },
  { id: 'builder', description: 'Implement the approved design, accessibility, security headers, and release build.' },
  { id: 'optimizer', description: 'Verify discovery metadata, structured data, sitemaps, and search hygiene.' },
  { id: 'reviewer', description: 'Perform read-only adversarial pre-ship review against gates and evidence.' },
]);

function rebaseRefs(body, skillRef) {
  return body.replace(/\b(playbooks|checklists|prompts|templates|references|roles)\/([A-Za-z0-9_./-]+)/g, `${skillRef}/$1/$2`);
}

function claudeAgentMarkdown(role, body, skillRef) {
  const tools = role.id === 'reviewer'
    ? 'Read, Grep, Glob'
    : 'Read, Write, Edit, Glob, Grep, Bash';
  const lines = [
    '---',
    `name: website-${role.id}`,
    `description: "${role.description}"`,
    `tools: ${tools}`,
    '---',
    '',
    `<!-- Generated by website-build-skill for Claude Code. Canonical source: ${skillRef}/roles/${role.id}.md -->`,
    '',
    rebaseRefs(body, skillRef).trimEnd(),
    '',
  ];
  return Buffer.from(lines.join('\n'), 'utf8');
}

function codexAgentToml(role, body, skillRef) {
  const sandboxMode = role.id === 'reviewer' ? 'read-only' : 'workspace-write';
  const instructions = rebaseRefs(body, skillRef).trimEnd().replace(/'''/g, "''\\'");
  const lines = [
    `# Generated by website-build-skill for Codex. Canonical source: ${skillRef}/roles/${role.id}.md`,
    `name = "website-${role.id}"`,
    `description = "${role.description}"`,
    `sandbox_mode = "${sandboxMode}"`,
    `developer_instructions = '''`,
    instructions,
    `'''`,
    '',
  ];
  return Buffer.from(lines.join('\n'), 'utf8');
}

/**
 * Generate native subagent definition files for supported targets (claude-code, codex).
 * Returns an empty array for targets that rely on manual session relay.
 */
export function generateAgents(request = {}) {
  const { target, project, destination, rolesRoot } = request;
  if (!['claude-code', 'codex'].includes(target)) return [];
  if (!project || !destination) throw Error('generateAgents requires project and destination');

  const sourceDir = rolesRoot ?? owned(packageRoot, `${CORE}/roles`);
  const relSkill = relative(project, destination).split('\\').join('/') || '.';

  return ROLES.map(role => {
    const rolePath = resolve(sourceDir, `${role.id}.md`);
    const body = fs.readFileSync(rolePath, 'utf8');
    if (target === 'claude-code') {
      const relPath = join('.claude', 'agents', `website-${role.id}.md`);
      return {
        role: role.id,
        relPath,
        path: resolve(project, relPath),
        root: project,
        bytes: claudeAgentMarkdown(role, body, relSkill),
      };
    }
    const relPath = join('.codex', 'agents', `website-${role.id}.toml`);
    return {
      role: role.id,
      relPath,
      path: resolve(project, relPath),
      root: project,
      bytes: codexAgentToml(role, body, relSkill),
    };
  });
}
