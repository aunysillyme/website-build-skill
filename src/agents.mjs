import fs from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CORE, owned } from './bundle.mjs';
import { agentDirFor } from './catalog.mjs';

const packageRoot = fileURLToPath(new URL('../', import.meta.url));

export const ROLES = Object.freeze([
  { id: 'researcher', description: 'Research current web standards, stacks, and references before design or code.' },
  { id: 'coordinator', description: 'Confirm scope, track gates, and coordinate handoffs across stages.' },
  { id: 'designer', description: 'Extract brand tokens and produce three visual directions before site code.' },
  { id: 'graphics', description: 'Prepare visual assets, crop inspections, and responsive image deliverables.' },
  { id: 'builder', description: 'Implement the approved design, accessibility, security headers, and release build.' },
  { id: 'optimizer', description: 'Verify discovery metadata, structured data, sitemaps, and search hygiene.' },
  { id: 'reviewer', description: 'Perform read-only adversarial pre-ship review against gates and evidence.' },
]);

const GEMINI_READONLY_TOOLS = Object.freeze([
  'read_file',
  'grep_search',
  'glob',
  'list_directory',
  'google_web_search',
  'web_fetch',
]);

function rebaseRefs(body, skillRef) {
  return body.replace(
    /(?<![A-Za-z0-9_./-])(?:\.\.\/)?(?:(playbooks|checklists|prompts|templates|references|roles|archive)\/([A-Za-z0-9_./-]+)|(SKILL\.md)(?![A-Za-z0-9_.-]))/g,
    (_, dir, rest, skill) => (skill ? `${skillRef}/${skill}` : `${skillRef}/${dir}/${rest}`),
  );
}

function tomlEscapeBasic(value) {
  return value
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]/g, ch => {
      if (ch === '\b') return '\\b';
      if (ch === '\f') return '\\f';
      if (ch === '\n') return '\\n';
      if (ch === '\r') return '\\r';
      if (ch === '\t') return '\\t';
      return `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`;
    });
}

function tomlBasicMultiline(value) {
  const escaped = value
    .replace(/\r\n/g, '\n')
    .replace(/\\/g, '\\\\')
    .replace(/"{3,}|"+$/g, match => '\\"'.repeat(match.length))
    .replace(/[\x00-\x08\x0b\x0c\x0e-\x1f\x7f\r]/g, ch => {
      if (ch === '\b') return '\\b';
      if (ch === '\f') return '\\f';
      if (ch === '\r') return '\\r';
      return `\\u${ch.charCodeAt(0).toString(16).padStart(4, '0')}`;
    });
  return `"""\n${escaped}\n"""`;
}

function claudeAgentMarkdown(role, body, skillRef) {
  const lines = [
    '---',
    `name: website-${role.id}`,
    `description: "${role.description}"`,
    ...(role.id === 'reviewer' ? ['disallowedTools: Write, Edit, Bash'] : []),
    '---',
    '',
    `<!-- Generated by website-build-skill for Claude Code. Canonical source: ${skillRef}/roles/${role.id}.md -->`,
    '',
    rebaseRefs(body, skillRef).trimEnd(),
    '',
  ];
  return Buffer.from(lines.join('\n'), 'utf8');
}

function codexAgentToml(role, body, skillRef) {
  const instructions = rebaseRefs(body, skillRef).trimEnd();
  const lines = [
    `# Generated by website-build-skill for Codex. Canonical source: ${skillRef}/roles/${role.id}.md`,
    "# Subagents inherit the parent turn's sandbox and approval settings in Codex.",
    `name = "website-${role.id}"`,
    `description = "${tomlEscapeBasic(role.description)}"`,
    `developer_instructions = ${tomlBasicMultiline(instructions)}`,
    '',
  ];
  return Buffer.from(lines.join('\n'), 'utf8');
}

function geminiAgentMarkdown(role, body, skillRef) {
  const lines = [
    '---',
    `name: website-${role.id}`,
    `description: "${role.description}"`,
    ...(role.id === 'reviewer' ? ['tools:', ...GEMINI_READONLY_TOOLS.map(tool => `  - ${tool}`)] : []),
    '---',
    '',
    `<!-- Generated by website-build-skill for Gemini CLI. Canonical source: ${skillRef}/roles/${role.id}.md -->`,
    '',
    rebaseRefs(body, skillRef).trimEnd(),
    '',
  ];
  return Buffer.from(lines.join('\n'), 'utf8');
}

function antigravityAgentMarkdown(role, body, skillRef) {
  const isReviewer = role.id === 'reviewer';
  const lines = [
    '---',
    `name: website-${role.id}`,
    `description: "${role.description}"`,
    'subagent: true',
    'mainAgent: false',
    `commandExecutionPolicy: ${isReviewer ? '"off"' : 'sandbox'}`,
    ...(isReviewer ? ['tools: [read_file, search_web]'] : []),
    '---',
    '',
    `<!-- Generated by website-build-skill for Google Antigravity. Canonical source: ${skillRef}/roles/${role.id}.md -->`,
    '',
    rebaseRefs(body, skillRef).trimEnd(),
    '',
  ];
  return Buffer.from(lines.join('\n'), 'utf8');
}

/**
 * Generate native subagent definition files for supported targets (claude-code, codex, gemini-cli, antigravity).
 * Returns an empty array for targets that rely on manual session relay.
 */
export function generateAgents(request = {}) {
  const { target, project, destination, scope = 'project', rolesRoot } = request;
  const agentDir = agentDirFor(target, scope);
  if (!agentDir) return [];
  if (!project || !destination) throw Error('generateAgents requires project and destination');

  const sourceDir = rolesRoot ?? owned(packageRoot, `${CORE}/roles`);
  const relSkill = relative(project, destination).split('\\').join('/') || '.';
  const dirSegments = agentDir.split('/');

  return ROLES.map(role => {
    const rolePath = resolve(sourceDir, `${role.id}.md`);
    const body = fs.readFileSync(rolePath, 'utf8');
    const isCodex = target === 'codex';
    const relPath = join(...dirSegments, `website-${role.id}.${isCodex ? 'toml' : 'md'}`);
    const bytes = target === 'claude-code'
      ? claudeAgentMarkdown(role, body, relSkill)
      : target === 'codex'
        ? codexAgentToml(role, body, relSkill)
        : target === 'gemini-cli'
          ? geminiAgentMarkdown(role, body, relSkill)
          : antigravityAgentMarkdown(role, body, relSkill);
    return {
      role: role.id,
      relPath,
      path: resolve(project, relPath),
      root: project,
      bytes,
    };
  });
}
